type Keys = keyof (typeof ui)['es'];

export function useTranslations(lang: Lang) {
  return <K extends Keys>(key: K): (typeof ui)['es'][K] => (ui[lang][key] ?? ui[defaultLang][key]) as (typeof ui)['es'][K];
}

/** Path for `path` (always written without the language prefix) in `lang`. */
export function localePath(lang: Lang, path = '/') {
  const clean = path.startsWith('/') ? path : `/${path}`;
  return lang === defaultLang ? clean : `/${lang}${clean === '/' ? '/' : clean}`;
}

/** Strip the language prefix from a pathname. */
export function stripLang(pathname: string) {
  return pathname.replace(/^\/en(?=\/|$)/, '') || '/';
}

export function pick<T>(value: Record<Lang, T>, lang: Lang): T {
  return value[lang] ?? value[defaultLang];
}
